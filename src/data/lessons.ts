const DAY_MS = 86_400_000
// This anchor opens the current launch day with physics, then advances through every field before repeating.
const ROTATION_START = Date.UTC(2026, 0, 14)

export function dayNumber(date: Date): number {
  const utcDay = Date.UTC(date.getFullYear(), date.getMonth(), date.getDate())
  return Math.floor((utcDay - ROTATION_START) / DAY_MS)
}

export function getDailyLesson(date = new Date()): Lesson {
  const index = ((dayNumber(date) % lessons.length) + lessons.length) % lessons.length
  return lessons[index]
}

export function getLessonById(id: string): Lesson | undefined {
  return lessons.find((lesson) => lesson.id === id)
}
